// Turns validated manifests into supabase/seed.sql, so partners, CI and the
// editor all start from the same Episode 1 content.

/** @param {unknown} value */
function literal(value) {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (Array.isArray(value) && value.every((item) => typeof item === "string")) {
    return value.length === 0 ? "'{}'" : `array[${value.map(literal).join(", ")}]`;
  }
  if (typeof value === "object") return `${literal(JSON.stringify(value))}::jsonb`;
  return `'${String(value).replaceAll("'", "''")}'`;
}

/**
 * @param {Array<{episodeId: string, manifestVersion: number, title: string, scenes: Array<Record<string, unknown>>}>} manifests
 * @returns {string}
 */
export function buildSeedSql(manifests) {
  const out = [
    "-- Generated by scripts/content/generate-seed.mjs from src/content/*.manifest.json. Do not edit by hand.",
  ];
  for (const manifest of manifests) {
    out.push(
      `insert into public.episodes (id, title, manifest_version, published_manifest, published_at) values (${literal(manifest.episodeId)}, ${literal(manifest.title)}, ${manifest.manifestVersion}, ${literal(manifest)}, now()) on conflict (id) do nothing;`,
    );
    for (const s of manifest.scenes) {
      const values = [
        manifest.episodeId, s.id, s.order, s.type, s.title, s.part, s.durationSec, s.required,
        s.prerequisites, s.checkpoint, s.forCheckpoint, s.beat, s.source, s.lines, s.bridge,
      ].map(literal);
      out.push(
        `insert into public.scenes (episode_id, id, position, type, title, part, duration_sec, required, prerequisites, checkpoint, for_checkpoint, beat, source, lines, bridge) values (${values.join(", ")}) on conflict (episode_id, id) do nothing;`,
      );
    }
  }
  return out.join("\n") + "\n";
}
